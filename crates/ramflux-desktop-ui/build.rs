//! Build steps of the UI crate:
//!
//! - Records the source revision as `RAMFLUX_DESKTOP_BUILD_REV` when the build
//!   environment (the macOS packaging script) did not already set it, so every
//!   build reports its commit.
//! - Compiles the string catalogues (`locales/<tag>.json`, one per locale) into
//!   sorted static tables (`$OUT_DIR/catalog.rs`). A catalogue that is not a
//!   flat JSON object of strings and nulls fails the build. The `card_gallery.*`
//!   keys are left out of the tables unless the `card-gallery` feature is on.
//! - Fails the build when a translation key written as a literal in `src/` is
//!   missing from the English catalogue, so a typo in a key never compiles.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    let manifest = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").unwrap_or_default());
    if let Err(error) = catalogues(&manifest) {
        eprintln!("error: {error}");
        std::process::exit(1);
    }
    build_rev();
}

fn build_rev() {
    println!("cargo:rerun-if-env-changed=RAMFLUX_DESKTOP_BUILD_REV");
    if std::env::var_os("RAMFLUX_DESKTOP_BUILD_REV").is_some() {
        return;
    }
    let Some(rev) = git(&["rev-parse", "HEAD"]) else { return };
    println!("cargo:rustc-env=RAMFLUX_DESKTOP_BUILD_REV={rev}");
    if let Some(git_dir) = git(&["rev-parse", "--absolute-git-dir"]) {
        println!("cargo:rerun-if-changed={git_dir}/HEAD");
    }
}

fn git(args: &[&str]) -> Option<String> {
    let output = Command::new("git").args(args).output().ok()?;
    if !output.status.success() {
        return None;
    }
    let text = String::from_utf8(output.stdout).ok()?.trim().to_owned();
    (!text.is_empty()).then_some(text)
}

/// One catalogue: key -> text, `None` for a key that is not translated yet.
type Catalogue = BTreeMap<String, Option<String>>;

fn catalogues(manifest: &Path) -> Result<(), String> {
    let dir = manifest.join("locales");
    println!("cargo:rerun-if-changed={}", dir.display());
    println!("cargo:rerun-if-changed={}", manifest.join("src").display());
    let mut catalogues: BTreeMap<String, Catalogue> = BTreeMap::new();
    let entries = std::fs::read_dir(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    for entry in entries.flatten() {
        let path = entry.path();
        if path.extension().is_none_or(|ext| ext != "json") {
            continue;
        }
        let tag = path.file_stem().and_then(|s| s.to_str()).unwrap_or_default().to_owned();
        catalogues.insert(tag, read_catalogue(&path)?);
    }
    let english = catalogues.get("en").ok_or("locales/en.json (the source locale) is missing")?;
    check_literal_keys(&manifest.join("src"), english)?;
    let mut out = String::from(
        "// Generated by build.rs from locales/*.json; do not edit.\n\n\
         /// Every catalogue: its tag and its translated entries, sorted by key.\n\
         pub(crate) static CATALOGUES: &[(&str, &[(&str, &str)])] = &[\n",
    );
    // The card gallery's strings (`card_gallery.*`) are compiled in only with
    // its feature; a release catalogue never carries them.
    let gallery = std::env::var_os("CARGO_FEATURE_CARD_GALLERY").is_some();
    for (tag, catalogue) in &catalogues {
        let _ = writeln!(out, "    ({tag:?}, &[");
        for (key, text) in catalogue {
            if key.starts_with("card_gallery.") && !gallery {
                continue;
            }
            if let Some(text) = text {
                let _ = writeln!(out, "        ({key:?}, {text:?}),");
            }
        }
        out.push_str("    ]),\n");
    }
    out.push_str("];\n");
    let target = PathBuf::from(std::env::var_os("OUT_DIR").unwrap_or_default()).join("catalog.rs");
    std::fs::write(&target, out).map_err(|e| format!("{}: {e}", target.display()))
}

fn read_catalogue(path: &Path) -> Result<Catalogue, String> {
    let text = std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
    let value: serde_json::Value =
        serde_json::from_str(&text).map_err(|e| format!("{}: {e}", path.display()))?;
    let serde_json::Value::Object(map) = value else {
        return Err(format!("{}: a catalogue is one JSON object", path.display()));
    };
    map.into_iter()
        .map(|(key, value)| match value {
            serde_json::Value::String(text) => Ok((key, Some(text))),
            serde_json::Value::Null => Ok((key, None)),
            _ => Err(format!("{}: {key} must be a string or null", path.display())),
        })
        .collect()
}

/// Whether `literal` is shaped like a translation key: dot-separated
/// segments of lowercase ASCII letters, digits and underscores.
fn is_key(literal: &str) -> bool {
    literal.contains('.')
        && literal.split('.').all(|part| {
            !part.is_empty()
                && part.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
        })
}

/// Every string literal in `src/` shaped like a key whose first segment is a
/// top-level group of the English catalogue must be a key, or the base of a
/// plural message (`key.other`).
fn check_literal_keys(src: &Path, english: &Catalogue) -> Result<(), String> {
    let groups: BTreeSet<&str> = english.keys().filter_map(|k| k.split('.').next()).collect();
    let mut files = Vec::new();
    rust_files(src, &mut files);
    let mut missing = BTreeSet::new();
    for file in files {
        let text =
            std::fs::read_to_string(&file).map_err(|e| format!("{}: {e}", file.display()))?;
        for literal in text.split('"').skip(1).step_by(2) {
            let group = literal.split('.').next().unwrap_or_default();
            let known =
                english.contains_key(literal) || english.contains_key(&format!("{literal}.other"));
            if is_key(literal) && groups.contains(group) && !known {
                missing.insert(format!("{} uses {literal}", file.display()));
            }
        }
    }
    if missing.is_empty() {
        return Ok(());
    }
    let list: Vec<String> = missing.into_iter().collect();
    Err(format!("translation keys missing from locales/en.json: {}", list.join("; ")))
}

fn rust_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(dir) else { return };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            rust_files(&path, out);
        } else if path.extension().is_some_and(|e| e == "rs") {
            out.push(path);
        }
    }
}
